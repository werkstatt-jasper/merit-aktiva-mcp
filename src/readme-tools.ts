export const README_TOOLS_START = "<!-- tools:start (generated by npm run docs:readme) -->";
export const README_TOOLS_END = "<!-- tools:end -->";
const SUMMARY_MAX = 160;

export interface ToolGroup {
  title: string;
  tools: Record<string, { description: string }>;
}

/** Tool modules in README order. The factories only keep the client; nothing is called. */
export function readmeToolGroups(): ToolGroup[] {
  const client = {} as MeritClient;
  return [
    { title: "Customers", tools: createCustomerTools(client) },
    { title: "Vendors", tools: createVendorTools(client) },
    { title: "Sales invoices", tools: createSalesInvoiceTools(client) },
    { title: "Sales offers", tools: createSalesOfferTools(client) },
    { title: "Payments", tools: createPaymentTools(client) },
    { title: "Purchases", tools: createPurchaseInvoiceTools(client) },
    { title: "General ledger", tools: createGlTransactionTools(client) },
    { title: "Accounts", tools: createAccountTools(client) },
    { title: "Taxes", tools: createTaxTools(client) },
    { title: "Items", tools: createItemTools(client) },
    { title: "Reference data", tools: createReferenceDataTools(client) },
    { title: "Reports", tools: createReportTools(client) },
    { title: "Recurring invoices", tools: createRecurringInvoiceTools(client) },
    { title: "Inventory", tools: createInventoryTools(client) },
    { title: "Fixed assets", tools: createFixedAssetTools(client) },
    { title: "Prices and discounts", tools: createPriceTools(client) },
  ];
}

/** First sentence of a tool description, on one line, safe inside a Markdown table cell. */
export function toolSummary(description: string): string {
  const flat = description.replace(/\s+/g, " ").trim();
  const sentence = flat.match(/^(.*?[.!?])(?=\s+[A-Z(`"]|$)/)?.[1] ?? flat;
  let summary = sentence;
  if (summary.length > SUMMARY_MAX) {
    const cut = summary.slice(0, SUMMARY_MAX - 1);
    summary = `${cut.slice(0, cut.lastIndexOf(" "))}…`;
  }
  return summary.replace(/\|/g, "\\|");
}

/** Markdown for the README tool section: a count, then one collapsible table per group. */
export function renderToolTable(groups: readonly ToolGroup[]): string {
  const total = groups.reduce((n, g) => n + Object.keys(g.tools).length, 0);
  const lines = [`**${total} tools.** Click a group to expand it.`, ""];
  for (const group of groups) {
    const entries = Object.entries(group.tools);
    lines.push(
      `<details><summary><b>${group.title}</b> (${entries.length})</summary>`,
      "",
      "| Tool | Description |",
      "|------|-------------|",
      ...entries.map(([name, tool]) => `| \`${name}\` | ${toolSummary(tool.description)} |`),
      "",
      "</details>",
      "",
    );
  }
  return lines.join("\n").trimEnd();
}

/** Replaces the text between the README tool markers. */
export function replaceToolTable(readme: string, table: string): string {
  const start = readme.indexOf(README_TOOLS_START);
  const end = readme.indexOf(README_TOOLS_END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error("README is missing the tools:start / tools:end markers");
  }
  return `${readme.slice(0, start + README_TOOLS_START.length)}\n${table}\n${readme.slice(end)}`;
}

/** Rewrites the tool table in the README at `path`. Returns true when the file changed. */
export function writeReadmeToolTable(path: string): boolean {
  const readme = readFileSync(path, "utf8");
  const next = replaceToolTable(readme, renderToolTable(readmeToolGroups()));
  if (next === readme) {
    return false;
  }
  writeFileSync(path, next);
  return true;
}
